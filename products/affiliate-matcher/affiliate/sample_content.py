#: 어느 원고인지 알아보는 실마리.
_HINTS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("캠핑", ("캠핑", "텐트", "침낭", "랜턴")),
    ("홈카페", ("홈카페", "원두", "그라인더", "드립")),
    ("홈트", ("홈트", "저항밴드", "덤벨", "스쿼트")),
)


def _pick(text: str) -> dict:
    """원고에서 실마리를 찾아 어떤 고정값을 줄지 고른다."""
    best_key, best_hits = "", 0
    for key, words in _HINTS:
        hits = sum(1 for word in words if word in text)
        if hits > best_hits:
            best_key, best_hits = key, hits
    if best_key:
        return FIXTURES[best_key]
    return {
        "title": "",
        "summary": "모의 실행이라 원고를 실제로 읽지 않았습니다",
        "medium": "블로그",
        "mentions": [
            _m(0, "(모의 실행 예시입니다. 실제 원고를 읽은 결과가 아닙니다.)",
               "생활용품", ["예시 키워드1", "예시 키워드2", "예시 키워드3"], 4,
               "여기에 상품을 소개하는 문장이 들어갑니다.",
               "모의 실행 고정값"),
        ],
    }


def _paragraph_count(user: str) -> int:
    match = re.search(r"\[문단 수\]\s*(\d+)", user)
    return int(match.group(1)) if match else 1


def fake_ask(system: str, user: str, **kwargs) -> dict:
    """`shared.llm.ask` 자리에 끼우는 가짜. 고정값을 돌려준다."""
    data = _pick(user)
    limit = _paragraph_count(user)
    mentions = [dict(item) for item in data["mentions"] if item["paragraph"] < limit]
    for item in mentions:
        if not item.get("insert_sentence"):
            # 낮은 강도라 어차피 계획에서 빠지지만, 규격은 지켜야 저장된다.
            item["insert_sentence"] = "(강도가 낮아 삽입 문장을 만들지 않았습니다)"
    return {**data, "mentions": mentions}
