/** 교육자료 ②~⑤ 프로그램별 덱 — 13·14·15·16번. */
const path = require("path");
const K = require("./build_training_decks.js");

/** 공통 뼈대: 파는 것 → 설치 → 관리자 → 클라이언트 → 사례 → FAQ → 조심할 것 */
function buildDeck(spec) {
  const p = K.deck();

  K.cover(p, {
    number: spec.number,
    title: spec.title,
    subtitle: spec.subtitle,
    tag: `교육자료 · ${spec.number}번 · 2026-09-18 기준`,
  });

  K.cards(p, {
    kicker: "이 상품이 파는 것",
    title: spec.sellTitle,
    intro: spec.sellIntro,
    cols: 2,
    items: spec.sells,
  });

  K.table(p, {
    kicker: "설치와 준비",
    title: "쓰기 전에 무엇이 필요한가",
    headers: ["무엇", "왜 필요한가", "비용", "걸리는 시간"],
    widths: [3.0, 5.6, 1.9, 1.6],
    rows: spec.needs,
    note: spec.needsNote,
  });

  K.shot(p, {
    kicker: "관리자 모드",
    title: spec.adminTitle,
    image: `${spec.slug}_admin.png`,
    caption: `/apps/${spec.id}/admin — 통합 대시보드에서 [관리자 모드 ↗] 로 엽니다.`,
    notes: spec.adminNotes,
  });

  if (spec.deepImage) {
    K.shot(p, {
      kicker: "관리자 모드",
      title: spec.deepTitle,
      image: spec.deepImage,
      caption: spec.deepCaption,
      notes: spec.deepNotes,
    });
  }

  K.shot(p, {
    kicker: "클라이언트 모드",
    title: spec.clientTitle,
    image: `${spec.slug}_client.png`,
    caption: `/apps/${spec.id}/client — 내가 미리 보는 고객 화면입니다. ` +
             `관리자 모드에서 관리자 기능만 뺀 같은 화면입니다.`,
    notes: spec.clientNotes,
  });

  // ── 여기부터는 16종이 똑같다. 한 번 배우면 나머지 열다섯에 그대로 쓴다.
  K.shot(p, {
    kicker: "고객에게 넘기기",
    title: "고객은 이 문으로 들어옵니다",
    image: `${spec.slug}_door.png`,
    caption: `/c/${spec.id} — 대시보드 접속 코드가 필요 없는 유일한 주소입니다.`,
    notes: [
      "고객에게 /apps/… 주소를 보내면 안 됩니다. 그 주소는 내 대시보드 접속 코드가 있어야 열립니다.",
      "이 문은 이중키만 받습니다. 열린 것은 문이지 화면이 아닙니다.",
      "키를 발급하면 만들어지는 안내 메일에 이 주소가 이미 적혀 있습니다.",
    ],
  });

  K.shot(p, {
    kicker: "고객에게 넘기기",
    title: "접속키 — 이름과 이메일만 넣으면 끝",
    image: `${spec.slug}_keys.png`,
    caption: `/apps/${spec.id}/admin/t/keys — 1차키 1개 + 2차키 3개가 한 번에 나옵니다.`,
    notes: [
      "1차키는 사람 한 명당 하나입니다. 동시 접속 수를 세지 않습니다.",
      "2차키는 PC·노트북·휴대폰 세 개이고 기기당 한 세션입니다. 같은 키로 다른 기기에서 들어오면 먼저 있던 기기가 잠깁니다.",
      "⏸ 사용중지는 되돌아갑니다. 🗑 삭제는 두 번 눌러야 하고 되돌릴 수 없습니다.",
      "전체 초기화는 '초기화' 를 정확히 쳐야 버튼이 살아납니다.",
      "[전체 복사] 로 안내문을 통째로 복사해 카톡이나 메일로 보내시면 됩니다.",
    ],
  });

  if (spec.handNotes) {
    K.shot(p, {
      kicker: "미리 알아 둘 것",
      title: "프로그램이 대신 못 하는 일",
      image: `${spec.slug}_hand.png`,
      caption: `/apps/${spec.id}/admin/t/hand — 왜 손으로 해야 하는지가 같이 적혀 있습니다.`,
      notes: spec.handNotes,
    });
  }

  K.cards(p, {
    kicker: "실제 사용 사례",
    title: spec.caseTitle,
    intro: spec.caseIntro,
    cols: 2,
    items: spec.caseSteps,
  });

  K.table(p, {
    kicker: "자주 묻는 것",
    title: "이 질문은 반드시 받습니다",
    headers: ["질문", "이렇게 답하세요"],
    widths: [4.6, 7.5],
    rows: spec.faq,
  });

  K.cards(p, {
    kicker: "조심할 것",
    title: spec.cautionTitle,
    intro: spec.cautionIntro,
    cols: 2,
    items: spec.cautions,
  });

  K.closing(p, { title: "기억하실 것", lines: spec.closing });

  return p.writeFile({ fileName: path.join(K.OUT, spec.file) })
    .then((f) => console.log("만들었습니다:", path.basename(f)));
}

